import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8');
const html=read('analytics/expanded-records.html');
const js=read('assets/expanded-records.mjs');
const portfolio=html.indexOf('id="manager-record-portfolio"');
const selector=html.indexOf('id="expanded-manager"');
const spotlight=html.indexOf('id="expanded-spotlight"');
const lab=html.indexOf('id="lab-heading"');
const explorer=html.indexOf('id="expanded-records-explorer"');
assert(portfolio>=0&&selector>portfolio&&spotlight>selector,'Portfolio selector and results must render together');
assert(lab>spotlight&&explorer>lab,'Manager portfolio must come before Expanded Records Lab');
assert.equal(html.split('id="expanded-manager"').length-1,1,'Manager selector must be unique');
assert.equal(html.split('id="expanded-spotlight"').length-1,1,'Manager portfolio results must be unique');
assert(js.includes('portfolio.querySelector("#expanded-manager")'),'Manager control must remain connected');
assert(js.includes('portfolio.querySelector("#expanded-spotlight")'),'Manager results must populate the first section');
assert(js.includes('let selectedManager=canonical.includes(requestedManager)'),'Direct manager links must hydrate');
assert(js.includes('requestedManager==="Thommy"?"Tom":"Stilly"'),'Thommy identity alias and default selection must work');
assert(js.includes('manager.addEventListener("change"'),'Manager picker must trigger an updated portfolio');
assert(js.includes('managerLeagueHolders(data,selectedManager)'),'Portfolio must use verified rankings');
assert(js.includes('group.addEventListener("change"')&&js.includes('category.addEventListener("change"'),'Expanded Lab filters must remain usable');
assert(html.includes('2026 through Week 8'),'Archived 2026 coverage must be transparent');
console.log('PASS: manager portfolio leads, manager deep links hydrate, lab filters and source limits remain intact');
