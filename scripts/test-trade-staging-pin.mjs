import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const workflow=readFileSync(new URL('../.github/workflows/prepare-approved-trade-museum.yml',import.meta.url),'utf8');
const docs=readFileSync(new URL('../docs/WEEKLY_PUBLICATION.md',import.meta.url),'utf8');
assert.ok(workflow.includes('staging_commit:'),'Trade certification must require reviewed commit input');
assert.ok(workflow.includes('REVIEWED_STAGING_COMMIT: ${{ inputs.staging_commit }}'),'Trade approval must receive pinned staging SHA');
assert.ok(workflow.includes('[[ "$REVIEWED_STAGING_COMMIT" =~ ^[0-9a-f]{40}$ ]]'),'Malformed SHA must be rejected');
assert.ok(workflow.includes('[[ "$SOURCE_COMMIT" != "$REVIEWED_STAGING_COMMIT" ]]'),'Moved staging branch must block trade approval');
assert.ok(workflow.includes('git show "$SOURCE_COMMIT:${CERT}"'),'Certificate must be read at approved SHA');
assert.ok(workflow.includes('git show "$SOURCE_COMMIT:${RAW}"'),'Original trade receipts must be read at approved SHA');
assert.ok(!workflow.includes('git show "origin/automation/sleeper-weekly-stage:${RAW}"'),'Unpinned receipt reads are forbidden');
assert.ok(docs.includes('trade_staging_commit=<reviewed 40-character SHA>'),'Runbook must specify approval pin');
const accept=s=>/^[0-9a-f]{40}$/.test(s);
assert.equal(accept('a'.repeat(40)),true);
assert.equal(accept('a'.repeat(39)),false);
assert.equal(accept('A'.repeat(40)),false);
assert.equal(accept('z'.repeat(40)),false);
assert.notEqual('a'.repeat(40),'b'.repeat(40),'Staging branch movement must be distinguishable');
console.log('Trade museum certification source SHA pin contract passed.');
