import assert from 'node:assert/strict';
import fs from 'node:fs';
import {buildWatch} from './build-certified-record-watch.mjs';
const names=['Stilly','Stew','Thommy','Mitch','JMid','Scott','Stover','Kuhl','Tony','Birch'];
const fixtures=(year,weeks,results)=>Array.from({length:weeks},(_,i)=>names.slice(0,5).map((home,j)=>({year,week:i+1,stage:'regular',home,away:names[j+5],homeScore:results(i,j)==='W'?100:results(i,j)==='T'?90:80,awayScore:90}))).flat();
const historical=fixtures(2025,5,(i,j)=>j===0?'W':(i+j)%2?'W':'L');
const active=fixtures(2026,4,(i,j)=>j===0?'W':(i+j)%2?'W':'L');
const options={year:2026,week:4,regularSeasonWeeks:6};
const ledger={games:[...historical,...active]};
const report=buildWatch(ledger,options);
const win=report.research.find(e=>e.manager==='Stilly'&&e.id==='single-season-regular-winning-streak');
assert.equal(win.type,'approaching');assert.equal(win.toTie,1);assert.equal(win.toBreak,2);
assert.deepEqual(report.items,[],'No certificates means no public alerts');
const cert={categoryId:win.id,status:'certified',year:2026,throughWeek:4,ledgerSha256:report.ledgerSha256,approvedEventIds:[win.eventId],reviewReference:'synthetic test only'};
assert.equal(buildWatch(ledger,{...options,certificates:[cert]}).items.length,1);
for(const bad of [{...cert,throughWeek:3},{...cert,ledgerSha256:'wrong'},{...cert,status:'research'},{...cert,approvedEventIds:[]},{...cert,reviewReference:''}])assert.deepEqual(buildWatch(ledger,{...options,certificates:[bad]}).items,[]);
assert.equal(buildWatch({games:[...ledger.games,active[0]]},options).status,'withheld');
assert.equal(buildWatch({games:ledger.games.slice(0,-1)},options).status,'withheld');
assert.equal(buildWatch(ledger,{...options,week:3}).status,'withheld');
assert.equal(buildWatch(ledger,{...options,regularSeasonWeeks:4}).research.some(e=>e.type==='approaching'),false);
const longer=fixtures(2026,6,(i,j)=>j===0?'W':(i+j)%2?'W':'L');
const tied=buildWatch({games:[...historical,...longer.filter(g=>g.week<=5)]},{...options,week:5});
assert.equal(tied.research.find(e=>e.manager==='Stilly').type,'tied');
const broken=buildWatch({games:[...historical,...longer]},{...options,week:6});
assert.equal(broken.research.find(e=>e.manager==='Stilly').type,'extended');
const ties=fixtures(2026,4,(i,j)=>j===0?(i===2?'T':'W'):(i+j)%2?'W':'L');
assert(!buildWatch({games:[...historical,...ties]},options).research.some(e=>e.manager==='Stilly'));
const reversed={games:ledger.games.map(g=>({...g,home:g.away,away:g.home,homeScore:g.awayScore,awayScore:g.homeScore}))};
assert.deepEqual(buildWatch(reversed,options).research.map(e=>e.eventId).sort(),report.research.map(e=>e.eventId).sort());
// Career categories are distinct from the single-season categories.
const careerFixture=fixtures(2025,14,(i,j)=>j===0?'W':(i+j)%2?'W':'L');
const bridged=buildWatch({games:[...careerFixture,...active]},options);
const careerWin=bridged.research.find(e=>e.manager==='Stilly'&&e.id==='career-regular-winning-streak');
assert.equal(careerWin.run,18);assert.equal(careerWin.startYear,2025);assert.equal(careerWin.startWeek,1);
assert.equal(careerWin.type,'extended');
const gapFixture=careerFixture.filter(g=>!(g.week===7&&g.home==='Stilly'));
const gapReport=buildWatch({games:[...gapFixture,...active]},options);
assert(!gapReport.research.some(e=>e.manager==='Stilly'&&e.id==='career-regular-winning-streak'&&e.startYear===2025));
const milestoneHistory=fixtures(2024,14,()=> 'W').concat(fixtures(2025,14,()=> 'W'));
const milestoneNow=fixtures(2026,2,()=> 'W');
const milestoneReport=buildWatch({games:[...milestoneHistory,...milestoneNow]},{year:2026,week:2,regularSeasonWeeks:14});
assert(!milestoneReport.research.some(e=>e.type==='milestone-achieved'&&e.target===25),'Already achieved milestones must not repeat');
const crossingHistory=fixtures(2024,12,()=> 'W').concat(fixtures(2025,12,()=> 'W'));
const crossing=buildWatch({games:[...crossingHistory,...fixtures(2026,1,()=> 'W')]},{year:2026,week:1,regularSeasonWeeks:14});
assert(crossing.research.some(e=>e.manager==='Stilly'&&e.id==='career-win-milestone'&&e.target===25&&e.type==='milestone-achieved'));
assert(crossing.research.some(e=>e.manager==='Scott'&&e.id==='career-game-milestone'&&e.target===25&&e.type==='milestone-achieved'));
assert(!crossing.research.some(e=>e.id==='career-points-milestone'&&e.type==='milestone-approaching'));
// Scoring crossings use pre-week evidence; equal scores share the record.
const scoringHistory=fixtures(2025,1,()=> 'W');
const scoringNow=fixtures(2026,1,()=> 'W').map((g,i)=>({...g,homeScore:i<2?200:100}));
const scoring=buildWatch({games:[...scoringHistory,...scoringNow]},{year:2026,week:1,regularSeasonWeeks:14});
const high=scoring.research.filter(e=>e.id==='weekly-highest-score');
assert.equal(high.length,2);assert(high.every(e=>e.type==='broken'&&e.value===200&&e.priorRecord===100));
assert.deepEqual(scoring.items,[]);
const same=buildWatch({games:[...scoringHistory,...fixtures(2026,1,()=> 'W')]},{year:2026,week:1,regularSeasonWeeks:14});
assert(same.research.filter(e=>e.id==='weekly-highest-score').every(e=>e.type==='tied'));
const repeatHistory=fixtures(2025,9,()=> 'W');
const repeat=buildWatch({games:[...repeatHistory,...fixtures(2026,1,()=> 'W')]},{year:2026,week:1,regularSeasonWeeks:14});
const meetings=repeat.research.filter(e=>e.id==='rivalry-meetings-milestone');
assert.equal(meetings.length,5);assert(meetings.every(e=>e.participants.length===2&&e.value===10));
assert.equal(new Set(meetings.map(e=>e.eventId)).size,5);
const rivalWins=repeat.research.filter(e=>e.id==='rivalry-wins-milestone');
assert.equal(rivalWins.length,5);assert(rivalWins.every(e=>e.participants.length===1&&e.value===10));
assert.equal(repeat.research.filter(e=>e.id==='career-weekly-high-titles').length,5);
assert.equal(repeat.research.filter(e=>e.id==='career-weekly-low-titles').length,5);
const read=p=>JSON.parse(fs.readFileSync(p,'utf8'));
const real=read('data/unified_record_book_2016_2026.json'),audit=read('data/week14_2020_2021_stage_classification_audit_v1.json');
const norm=n=>n==='Tom'?'Thommy':n;
const excludedKeys=audit.years.flatMap(y=>y.week14Games.map(g=>JSON.stringify([y.year,g.week,...[norm(g.home),norm(g.away)].sort()])));
const week=Math.max(...real.games.filter(g=>g.year===2026&&g.stage==='regular').map(g=>g.week));
const current=buildWatch(real,{year:2026,week,regularSeasonWeeks:14,excludedKeys});
assert.deepEqual(current.items,[]);
if(week===11){
 const kuhl=current.research.find(e=>e.manager==='Kuhl'&&e.id==='single-season-regular-losing-streak');
 assert.equal(kuhl.type,'tied');assert.equal(kuhl.run,11);assert.equal(kuhl.toBreak,1);
 assert(!current.research.some(e=>e.manager==='Stew'&&e.id==='single-season-regular-winning-streak'));
}
console.log('Record Watch tests passed: cutoff, duplicates, ties, reachability, review gating, ownership and current-week evidence');
